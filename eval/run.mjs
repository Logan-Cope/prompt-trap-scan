// Runs every fixture in a real browser and prints the detection table.
// Usage: node eval/run.mjs [--write]   (--write refreshes docs/EVAL.md)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'corpus/manifest.json'), 'utf8'));

export async function runCorpus() {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  await page.goto('about:blank');
  await page.addScriptTag({ path: path.join(root, 'src/scan.js') });
  await page.addScriptTag({ path: path.join(root, 'src/eval-core.js') });
  const rows = [];
  for (const entry of manifest.fixtures) {
    await page.goto(pathToFileURL(path.join(root, 'corpus', entry.file)).href);
    await page.addScriptTag({ path: path.join(root, 'src/scan.js') });
    await page.addScriptTag({ path: path.join(root, 'src/eval-core.js') });
    const row = await page.evaluate((e) => {
      const report = PromptTrapScan.scan(document);
      const naive = PromptTrapEval.naiveScan(document);
      return { ...PromptTrapEval.score(e, report, naive), report };
    }, entry);
    rows.push(row);
  }
  await browser.close();
  const summary = await summarizeInNode(rows);
  return { rows, summary };
}

async function summarizeInNode(rows) {
  const require = (await import('node:module')).createRequire(import.meta.url);
  return require('../src/eval-core.js').summarize(rows);
}

export function renderMarkdown(rows, s) {
  const pct = (a, b) => (b ? Math.round((100 * a) / b) : 100) + '%';
  const lines = [];
  lines.push('| Measure | prompt-trap-scan | Naive baseline |', '|---|---|---|');
  lines.push(`| Planted traps found | ${s.found} of ${s.planted} (${pct(s.found, s.planted)}) | ${s.naiveFound} of ${s.planted} (${pct(s.naiveFound, s.planted)}) |`);
  lines.push(`| False trap flags on clean pages | ${s.falseFlags} across ${s.cleanPages} pages | ${s.naiveFalseFlags} across ${s.cleanPages} pages |`);
  lines.push(`| Screen-reader text routed to its own bucket | ${s.accessibilityRouted} of ${s.cleanPages} pages | not separated |`);
  lines.push('', '| Concealment method | Planted | Scanner | Naive |', '|---|---|---|---|');
  for (const [m, v] of Object.entries(s.byMethod)) lines.push(`| ${m} | ${v.n} | ${v.found} | ${v.naive} |`);
  const misses = rows.filter((r) => r.kind === 'limit');
  lines.push('', `Documented limits (not scored): ${misses.map((r) => `${r.id} reads \`${r.verdict}\``).join(', ')}.`);
  return lines.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { rows, summary: s } = await runCorpus();
  const md = renderMarkdown(rows, s);
  console.log(md);
  const bad = rows.flatMap((r) => r.planted.filter((p) => !p.found).map((p) => `${r.id}: ${p.fragment}`));
  const ok = s.found === s.planted && s.falseFlags === 0 && s.verdictsOk === s.cleanPages && s.accessibilityRouted === s.cleanPages && s.planted >= 15 && s.cleanPages >= 10;
  if (process.argv.includes('--write')) {
    fs.writeFileSync(path.join(root, 'docs/EVAL.md'), `# Evaluation\n\nGenerated by \`npm run eval:write\`. CI re-runs it and fails if this file is stale.\n\n${md}\n`);
  }
  if (!ok) {
    console.error('\nBAR NOT MET. Missed:', bad, 'false flags:', s.falseFlags);
    for (const r of rows.filter((r) => r.kind === 'clean' && (!r.accessibilityOk || !r.verdictOk || r.falseFlags))) console.error(r.id, r.verdict, JSON.stringify(r.report.counts));
    process.exit(1);
  }
}
